#!/usr/bin/env python3
"""Offlinka app icon: geometry -> SVG layers (design/appicon/) + Android adaptive icon XML (design/out/android/).

    python3 design/tools/appicon.py          # then: node design/tools/render-icons.cjs (PNG sizes)

The mark: an open paper book on forest green, the logo's orange peak above its spine (the i-dot of the
wordmark), a hard offset shadow like the drive's cards, faint contour lines behind. All on the 108-unit
Android adaptive canvas; the safe zone is the central circle of radius 33.
"""
import math
from pathlib import Path

D = Path(__file__).resolve().parent.parent
FOREST, FOREST_DARK, TOPO, PAPER, FIRE = "#1F3D2F", "#14291F", "#2A4D3C", "#F5F0E3", "#F26A1B"
SHADOW = "#132A1F"
SH = (2.2, 2.6)          # hard shadow offset in canvas units

LEFT = "M{a} 55C46 50.5 37.5 49.5 30 52L30 74C37.5 71.5 46 72.5 {a} 77.5Z"
RIGHT = "M{b} 55C62 50.5 70.5 49.5 78 52L78 74C70.5 71.5 62 72.5 {b} 77.5Z"
PEAK = "M54 30L63.75 45L44.25 45Z"


def book_paths(dx=0.0, dy=0.0):
    """Left page, right page, peak; optionally translated (for the shadow)."""
    import re

    def shift(d):
        i = 0
        def repl(m):
            nonlocal i
            v = float(m.group(0)) + (dx if i % 2 == 0 else dy)
            i += 1
            return ("%.2f" % v).rstrip("0").rstrip(".")
        return re.sub(r"-?\d+(?:\.\d+)?", repl, d)
    paths = [LEFT.format(a=51.75), RIGHT.format(b=56.25), PEAK]
    return [shift(p) for p in paths]


def contours():
    """Faint topo rings around a hill top, upper left (like the drive's hero texture)."""
    rings = []
    cx, cy = 34.0, 36.0
    for k, r0 in enumerate([9, 17, 26, 36, 47, 59, 72, 86]):
        pts, n = [], 48
        for j in range(n):
            t = 2 * math.pi * j / n
            r = r0 * (1 + 0.10 * math.sin(2 * t + 0.6 + k * 0.35) + 0.06 * math.sin(3 * t + 1.9 - k * 0.2)
                      + 0.03 * math.sin(5 * t + k))
            pts.append((cx + r * math.cos(t) * 1.08, cy + r * math.sin(t)))
        # closed Catmull-Rom spline -> cubic Beziers: smooth at any size, small path data
        f = lambda v: f"{v:.1f}"
        d = f"M{f(pts[0][0])} {f(pts[0][1])}"
        for j in range(n):
            p0, p1, p2, p3 = pts[j - 1], pts[j], pts[(j + 1) % n], pts[(j + 2) % n]
            c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
            c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
            d += f"C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(p2[0])} {f(p2[1])}"
        rings.append(d + "Z")
    return rings


def svg(body, size=108, bg=None):
    rect = f'<rect width="{size}" height="{size}" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">'
            f"{rect}{body}</svg>\n")


def main():
    out = D / "appicon"
    out.mkdir(exist_ok=True)
    rings = contours()
    shadow = book_paths(*SH)
    book = book_paths()

    def layer_bg(fill=FOREST, line=TOPO):
        return f'<rect width="108" height="108" fill="{fill}"/>' + "".join(
            f'<path d="{d}" fill="none" stroke="{line}" stroke-width="0.75"/>' for d in rings)

    def layer_fg(page=PAPER, peak=FIRE, sh=SHADOW):
        s = "".join(f'<path d="{d}" fill="{sh}"/>' for d in shadow) if sh else ""
        return s + f'<path d="{book[0]}" fill="{page}"/><path d="{book[1]}" fill="{page}"/><path d="{book[2]}" fill="{peak}"/>'

    files = {
        "background.svg": svg(layer_bg()),
        "foreground.svg": svg(layer_fg()),
        "monochrome.svg": svg(layer_fg("#FFFFFF", "#FFFFFF", None)),
        # full-bleed squares for iOS / Play (the renderer scales them)
        "full-light.svg": svg(layer_bg() + layer_fg()),
        "full-dark.svg": svg(layer_bg("#0E1A13", "#1A2E23") + layer_fg(PAPER, FIRE, "#050D09")),
        "full-tinted.svg": svg(layer_bg("#000000", "#161616") + layer_fg("#D9D9D9", "#FFFFFF", None)),
    }
    for n, s in files.items():
        (out / n).write_text(s, encoding="utf-8")
        print("  wrote design/appicon/" + n)

    # Android adaptive icon: vector layers + mipmap-anydpi-v26 XMLs
    def vec(paths):
        x = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by design/tools/appicon.py. Do not edit by hand. -->",
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="108dp" android:height="108dp"',
             '    android:viewportWidth="108" android:viewportHeight="108">']
        for d, fill, stroke in paths:
            if stroke:
                x.append(f'    <path android:strokeColor="{stroke}" android:strokeWidth="0.75" android:pathData="{d}"/>')
            else:
                x.append(f'    <path android:fillColor="{fill}" android:pathData="{d}"/>')
        return "\n".join(x + ["</vector>", ""])

    a = D / "out" / "android"
    (a / "drawable").mkdir(parents=True, exist_ok=True)
    (a / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    bg = [("M0,0h108v108h-108z", FOREST, None)] + [(d, None, TOPO) for d in rings]
    fg = [(d, SHADOW, None) for d in shadow] + [(book[0], PAPER, None), (book[1], PAPER, None), (book[2], FIRE, None)]
    mono = [(book[0], "#FFFFFFFF", None), (book[1], "#FFFFFFFF", None), (book[2], "#FFFFFFFF", None)]
    (a / "drawable" / "ic_launcher_background.xml").write_text(vec(bg), encoding="utf-8")
    (a / "drawable" / "ic_launcher_foreground.xml").write_text(vec(fg), encoding="utf-8")
    (a / "drawable" / "ic_launcher_monochrome.xml").write_text(vec(mono), encoding="utf-8")
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                "<!-- Generated by design/tools/appicon.py. Do not edit by hand. -->\n"
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                "</adaptive-icon>\n")
    (a / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(adaptive, encoding="utf-8")
    (a / "mipmap-anydpi-v26" / "ic_launcher_round.xml").write_text(adaptive, encoding="utf-8")
    print("  wrote design/out/android/drawable/ic_launcher_{background,foreground,monochrome}.xml + mipmap-anydpi-v26/")


if __name__ == "__main__":
    main()
