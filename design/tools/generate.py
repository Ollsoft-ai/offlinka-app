def kebab(s):
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), s)


# --------------------------------------------------------------------------------------------- strings
NBSP = "\u00a0"


def typography(s, lang):
    """Typesetting rules; the sources keep plain spaces, outputs get U+00A0.
    Every language: licence names (CC BY-SA 4.0, SIL OFL 1.1), "© 2026" and "Ollcee s.r.o." never break.
    Czech/Slovak also: no break after a one-letter word or "po", between a number (or a {placeholder}) and
    the word or unit after it, in "USB kľúč" and in "iPhone 14" / "Android 8"."""
    s = re.sub(r"CC BY-SA (\d)", "CC" + NBSP + "BY-SA" + NBSP + r"\1", s)
    s = re.sub(r"SIL OFL (\d)", "SIL" + NBSP + "OFL" + NBSP + r"\1", s)
    s = re.sub(r"© (\d{4})", "©" + NBSP + r"\1", s)
    s = re.sub(r" (s\.r\.o\.)", NBSP + r"\1", s)
    if lang not in ("cs", "sk"):
        return s
    s = re.sub(r"(?<!\w)([KkSsVvZzOoUuAaIi]) ", r"\1" + NBSP, s)
    s = re.sub(r"(?<!\w)([Pp]o) ", r"\1" + NBSP, s)
    s = re.sub(r"(\d|\})[ ](%|GB|MB|kB|km\b|m\b)", r"\1" + NBSP + r"\2", s)
    s = re.sub(r"(?<![\w.,])(\d+|\{\w+\}) (?=[^\W\d_])", r"\1" + NBSP, s)
    s = re.sub(r"USB (kľúč\w*)", "USB" + NBSP + r"\1", s)
    s = re.sub(r"(iPhone|Android\w*) (\d+)", r"\1" + NBSP + r"\2", s)
    return s


def gen_strings():
    langs = ["cs", "sk", "en"]
    data = {l: load(f"strings/{l}.json") for l in langs}
    for l in langs:
        for k, v in list(data[l].items()):
            if k.startswith("_"):
                continue
            data[l][k] = {q: typography(t, l) for q, t in v.items()} if isinstance(v, dict) else typography(v, l)
    keys = [k for k in data["cs"] if not k.startswith("_")]
    for l in langs:
        missing = [k for k in keys if k not in data[l]]
        extra = [k for k in data[l] if k not in data["cs"] and not k.startswith("_")]
        assert not missing, f"{l}: missing {missing}"
        assert not extra, f"{l}: keys not in cs.json {extra}"
    for l in langs:
        for k in keys:
            for txt in (data[l][k].values() if isinstance(data[l][k], dict) else [data[l][k]]):
                assert "—" not in txt, f"{l}.{k}: em dash"
                assert not re.search("[\U0001F300-\U0001FAFF☀-➿]", txt), f"{l}.{k}: emoji"
                assert "Kiwix" not in txt or k.startswith("about_"), f"{l}.{k}: Kiwix outside About"
    hdr = HEADER.format(src="strings/<lang>.json")

    NUMERIC = ("n", "count", "current", "total")

    # placeholders: {n}/{count}/{current}/{total} = integer, any other {name} = text. Positions come from the cs string.
    def placeholders(k):
        v = data["cs"][k]
        src = " ".join(v.values()) if isinstance(v, dict) else v
        seen = []
        for m in re.finditer(r"\{(\w+)\}", src):
            if m.group(1) not in seen:
                seen.append(m.group(1))
        return seen

    def to_android(s, ph):
        s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
        s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        s = s.replace("\n", "\\n")
        if ph:
            s = s.replace("%", "%%")
        if s.startswith("@") or s.startswith("?"):
            s = "\\" + s
        for i, p in enumerate(ph, 1):
            s = s.replace("{" + p + "}", f"%{i}${'d' if p in NUMERIC else 's'}")
        return s

    def to_ios(s, ph):
        if ph:
            s = s.replace("%", "%%")
        for i, p in enumerate(ph, 1):
            s = s.replace("{" + p + "}", f"%{i}${'lld' if p in NUMERIC else '@'}")
        return s

    for l in langs:
        folder = "values" if l == "cs" else f"values-{l}"
        x = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {hdr} -->", "<resources>"]
        for k in keys:
            v, ph = data[l][k], placeholders(k)
            if isinstance(v, dict):
                x.append(f'    <plurals name="{k}">')
                for q in ("zero", "one", "two", "few", "many", "other"):
                    if q in v:
                        x.append(f'        <item quantity="{q}">{to_android(v[q], ph)}</item>')
                x.append("    </plurals>")
            else:
                fmt = ' formatted="false"' if (not ph and "%" in v) else ""
                x.append(f'    <string name="{k}"{fmt}>{to_android(v, ph)}</string>')
        x += ["</resources>", ""]
        write(f"android/{folder}/strings.xml", "\n".join(x))

    xc = {"sourceLanguage": "cs", "version": "1.0", "strings": {}}
    for k in keys:
        ph = placeholders(k)
        entry = {"extractionState": "manual", "localizations": {}}
        if "_comment_" + k in data["cs"]:
            entry["comment"] = data["cs"]["_comment_" + k]
        for l in langs:
            v = data[l][k]
            if isinstance(v, dict):
                entry["localizations"][l] = {"variations": {"plural": {
                    q: {"stringUnit": {"state": "translated", "value": to_ios(v[q], ph)}} for q in v}}}
            else:
                entry["localizations"][l] = {"stringUnit": {"state": "translated", "value": to_ios(v, ph)}}
        xc["strings"][k] = entry
    write("ios/Localizable.xcstrings", json.dumps(xc, ensure_ascii=False, indent=2) + "\n")
    (D / "mockups" / "assets").mkdir(parents=True, exist_ok=True)
    (D / "mockups" / "assets" / "strings.js").write_text(
        "// Generated by design/tools/generate.py from design/strings. Do not edit by hand.\nwindow.STRINGS = "
        + json.dumps({l: {k: v for k, v in data[l].items() if not k.startswith("_")} for l in langs}, ensure_ascii=False)
        + ";\n", encoding="utf-8")


