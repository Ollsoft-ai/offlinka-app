HEADER = "Generated by design/tools/generate.py from design/{src}. Do not edit by hand."


def load(p):
    return json.loads((D / p).read_text(encoding="utf-8"))


def write(path, text):
    path = OUT / path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print("  wrote", path.relative_to(D.parent))


def camel_to_pascal(s):
    return s[0].upper() + s[1:]


def argb(h):
    """'#RRGGBB' or '#AARRGGBB' -> (a, r, g, b) ints."""
    h = h.lstrip("#")
    if len(h) == 6:
        h = "FF" + h
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4, 6))


def kt_color(h):
    a, r, g, b = argb(h)
    return f"Color(0x{a:02X}{r:02X}{g:02X}{b:02X})"


def css_color(h):
    a, r, g, b = argb(h)
    if a == 255:
        return f"#{r:02X}{g:02X}{b:02X}"
    return f"rgba({r},{g},{b},{round(a / 255, 3)})"


def swift_hex(h):
    a, r, g, b = argb(h)
    return f"0x{r:02X}{g:02X}{b:02X}", round(a / 255, 3)


def num(v):
    return ("%g" % v)


