def shape_to_path(tag, a):
    """circle/rect/line/polyline/ellipse -> path data (Android vector drawables only take paths)."""
    f = lambda n, d=0.0: float(a.get(n, d))
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = f("cx"), f("cy"), f("r")
        return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0 1,0 {num(2 * r)},0a{num(r)},{num(r)} 0 1,0 {num(-2 * r)},0Z"
    if tag == "ellipse":
        cx, cy, rx, ry = f("cx"), f("cy"), f("rx"), f("ry")
        return f"M{num(cx - rx)},{num(cy)}a{num(rx)},{num(ry)} 0 1,0 {num(2 * rx)},0a{num(rx)},{num(ry)} 0 1,0 {num(-2 * rx)},0Z"
    if tag == "line":
        return f"M{num(f('x1'))},{num(f('y1'))}L{num(f('x2'))},{num(f('y2'))}"
    if tag in ("polyline", "polygon"):
        pts = re.findall(r"-?[\d.]+", a["points"])
        pairs = [f"{pts[i]},{pts[i + 1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y, w, h = f("x"), f("y"), f("width"), f("height")
        rx = f("rx", f("ry", 0))
        if not rx:
            return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
        r = min(rx, w / 2, h / 2)
        return (f"M{num(x + r)},{num(y)}h{num(w - 2 * r)}a{num(r)},{num(r)} 0 0,1 {num(r)},{num(r)}"
                f"v{num(h - 2 * r)}a{num(r)},{num(r)} 0 0,1 {num(-r)},{num(r)}h{num(-(w - 2 * r))}"
                f"a{num(r)},{num(r)} 0 0,1 {num(-r)},{num(-r)}v{num(-(h - 2 * r))}a{num(r)},{num(r)} 0 0,1 {num(r)},{num(-r)}Z")
    raise ValueError(tag)


def gen_icons():
    import xml.etree.ElementTree as ET
    src = sorted((D / "icons" / "svg").glob("*.svg"))
    names, sheet = [], []
    for p in src:
        name = p.stem
        assert re.fullmatch(r"[a-z0-9_]+", name), f"icon name must be snake_case: {name}"
        root = ET.parse(p).getroot()
        sw = root.get("stroke-width", "1.75")
        x = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- Generated by design/tools/generate.py from design/icons/svg/{p.name}. Do not edit by hand. -->",
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp" android:height="24dp"',
             '    android:viewportWidth="24" android:viewportHeight="24">']
        for el in root.iter():
            tag = el.tag.split("}")[-1]
            if tag in ("svg", "title", "desc", "g"):
                continue
            d = shape_to_path(tag, el.attrib)
            fill = "#FF000000" if el.get("fill") not in (None, "none") else "#00000000"
            stroked = el.get("stroke") != "none"
            attrs = f'android:fillColor="{fill}"'
            if stroked:
                attrs += (f' android:strokeColor="#FF000000" android:strokeWidth="{sw}"'
                          ' android:strokeLineCap="round" android:strokeLineJoin="round"')
            x.append(f'    <path {attrs} android:pathData="{d}"/>')
        x += ["</vector>", ""]
        write(f"android/drawable/ic_{name}.xml", "\n".join(x))
        # iOS: the SVG in an imageset, rendered as a template image (tinted like text). Xcode wants a plain colour.
        svg_text = p.read_text(encoding="utf-8").replace("currentColor", "#000000")
        write(f"ios/icons/Icons.xcassets/{name}.imageset/{name}.svg", svg_text)
        write(f"ios/icons/Icons.xcassets/{name}.imageset/Contents.json", json.dumps({
            "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"}
        }, indent=2) + "\n")
        names.append(name)
        sheet.append(f'<figure>{p.read_text(encoding="utf-8").strip()}<figcaption>{name}</figcaption></figure>')
    write("ios/icons/Icons.xcassets/Contents.json", json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    # icon bodies for the HTML mockups
    bodies = {}
    for p in src:
        t = p.read_text(encoding="utf-8")
        inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", t, flags=re.S)
        bodies[p.stem] = re.sub(r"<title>.*?</title>", "", inner)
    (D / "mockups" / "assets").mkdir(parents=True, exist_ok=True)
    (D / "mockups" / "assets" / "icons.js").write_text(
        "// Generated by design/tools/generate.py from design/icons/svg. Do not edit by hand.\nwindow.ICONS = "
        + json.dumps(bodies, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    # contact sheet for review: every icon at 24 and 48 px, light and dark
    (D / "icons" / "sheet.html").write_text(
        "<!doctype html><html lang=\"cs\"><head><meta charset=\"utf-8\"><title>Offlinka icons</title><style>"
        "body{margin:0;font:12px/1.3 system-ui,sans-serif}section{display:grid;grid-template-columns:repeat(8,1fr);"
        "gap:6px;padding:16px}.l{background:#F5F0E3;color:#17231C}.d{background:#0F1A14;color:#EEE8D8}"
        "figure{margin:0;display:flex;flex-direction:column;align-items:center;gap:6px;padding:8px 2px}"
        "figure svg{width:24px;height:24px}section.big figure svg{width:48px;height:48px}"
        "figcaption{font-size:10.5px;opacity:.7;text-align:center;word-break:break-all}</style></head><body>"
        f"<section class=\"l\">{''.join(sheet)}</section><section class=\"l big\">{''.join(sheet)}</section>"
        f"<section class=\"d\">{''.join(sheet)}</section></body></html>\n", encoding="utf-8")
    print(f"  {len(names)} icons (+ design/icons/sheet.html)")


