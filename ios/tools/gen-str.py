#!/usr/bin/env python3
"""Generates ios/Offlinka/Localization/Str.swift (typed string keys) from design/strings/cs.json.

The strings themselves live in design/ (source of truth for Android and iOS); the app target uses
design/out/ios/Localizable.xcstrings directly. Run after design adds or renames a key:
    python3 ios/tools/gen-str.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "design", "strings", "cs.json")
TARGET = os.path.join(ROOT, "ios", "Offlinka", "Localization", "Str.swift")
SWIFT_KEYWORDS = {"default", "case", "class", "func", "import", "in", "is", "let", "var", "return", "self", "struct", "enum", "protocol", "extension", "static", "where", "while", "for", "if", "else", "switch", "do", "try", "catch", "throw", "true", "false", "nil", "operator", "repeat", "break", "continue", "init", "deinit", "subscript", "typealias", "associatedtype", "inout", "internal", "private", "public", "open", "fileprivate", "as", "super", "guard", "defer", "fallthrough", "any", "some"}


def camel(key: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", key) if p]
    name = parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if name[0].isdigit():
        name = "k" + name
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def main() -> int:
    with open(SOURCE, encoding="utf-8") as f:
        strings = json.load(f)
    keys = [k for k in strings if not k.startswith("_")]
    lines = [
        "// Generated by ios/tools/gen-str.py from design/strings/cs.json. Do not edit by hand.",
        "// The texts are in design/out/ios/Localizable.xcstrings (cs, sk, en).",
        "",
        "/// Typed keys of every UI string. Use with `tr(.key)` / `tr(.key, args...)`.",
        "enum Str: String, CaseIterable, Sendable {",
    ]
    seen = set()
    for key in keys:
        name = camel(key)
        if name in seen:
            print(f"duplicate Swift name {name} for {key}", file=sys.stderr)
            return 1
        seen.add(name)
        value = strings[key]
        kind = " // plural" if isinstance(value, dict) else ""
        lines.append(f'    case {name} = "{key}"{kind}')
    lines.append("}")
    lines.append("")
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(keys)} keys -> {os.path.relpath(TARGET, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
