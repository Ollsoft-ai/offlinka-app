// ---- Design system from ../design (never copied by hand) ----------------------------------------
// design/out/android/*.kt: theme generated by the design agent (package cz.offlinka.app.ui.theme there,
// cz.offlinka.ui.theme here). design/fonts/*.ttf, design/out/android/values*/strings.xml and
// design/out/android/drawable*/ are added as generated resources.
val designDir: File = rootProject.projectDir.parentFile.resolve("design")

abstract class DesignKotlin : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val source: DirectoryProperty
    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val out = output.get().asFile.resolve("cz/offlinka/ui/theme")
        output.get().asFile.deleteRecursively()
        out.mkdirs()
        source.get().asFile.listFiles { f -> f.extension == "kt" }!!.forEach { f ->
            out.resolve(f.name).writeText(
                f.readText()
                    .replace("package cz.offlinka.app.ui.theme", "package cz.offlinka.ui.theme")
                    .replace("import cz.offlinka.app.R", "import cz.offlinka.ui.R"),
            )
        }
    }
}

abstract class DesignRes : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val androidOut: DirectoryProperty
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val fonts: DirectoryProperty
    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val out = output.get().asFile
        out.deleteRecursively()
        out.mkdirs()
        androidOut.get().asFile.listFiles { f -> f.isDirectory && (f.name.startsWith("values") || f.name.startsWith("drawable")) }!!
            .forEach { it.copyRecursively(out.resolve(it.name)) }
        val font = out.resolve("font").apply { mkdirs() }
        fonts.get().asFile.listFiles { f -> f.extension == "ttf" }!!.forEach { it.copyTo(font.resolve(it.name)) }
    }
}

val designKotlin = tasks.register<DesignKotlin>("designKotlin") {
    source.set(designDir.resolve("out/android"))
    output.set(layout.buildDirectory.dir("generated/design/kotlin"))
}
val designRes = tasks.register<DesignRes>("designRes") {
    androidOut.set(designDir.resolve("out/android"))
    fonts.set(designDir.resolve("fonts"))
    output.set(layout.buildDirectory.dir("generated/design/res"))
}

androidComponents {
    onVariants { variant ->
        variant.sources.kotlin?.addGeneratedSourceDirectory(designKotlin, DesignKotlin::output)
        variant.sources.res?.addGeneratedSourceDirectory(designRes, DesignRes::output)
    }
}
